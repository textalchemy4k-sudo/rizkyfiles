import * as THREE from 'three/webgpu';
import { buildWorld } from './world.js';
import { buildTown, ROADW } from './town.js';
const W = 1080, H = 1920;
const renderer = new THREE.WebGPURenderer({ antialias: true }); renderer.setPixelRatio(1); renderer.setSize(W, H); renderer.toneMapping = THREE.ACESFilmicToneMapping; renderer.shadowMap.enabled = true; document.body.appendChild(renderer.domElement); await renderer.init();
const dummy = new THREE.Scene(); const world = buildWorld(dummy);
const scene = new THREE.Scene(); const T = buildTown(scene, world.envDay); const camera = new THREE.PerspectiveCamera(45, W / H, 0.05, 9000);
const VIEWS = [[[1.5, 1.6, 30], [0, 2.5, -20], 55], [[-1.5, 1.3, 2], [ROADW + 2, 1.6, -4], 45], [[ROADW + 2, 2.5, 10], [ROADW + 5, 2.5, 0], 50], [[-3, 9, 40], [0, 2, -10], 50]];
window.renderFrame = async (f) => { const v = VIEWS[f]; camera.position.set(...v[0]); camera.lookAt(...v[1]); camera.fov = v[2]; camera.updateProjectionMatrix(); T.placeLight(new THREE.Vector3(...v[1])); await renderer.renderAsync(scene, camera); };
window.SCENE = { fps: 30, frames: VIEWS.length, width: W, height: H };
await window.renderFrame(0); window.ready = true;
